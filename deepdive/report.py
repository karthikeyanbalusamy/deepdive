"""Turns the writer's draft into the final Markdown report, and the report into a shareable web page.

This is the last safety check, in plain code: a sentence is kept only if every claim it cites was
verified. Its citations are the sources of those claims, so they always trace back to retrieved text.
"""

import html

import markdown

from deepdive.agents import Draft, Sentence

PAGE_STYLE = """
body { font-family: Segoe UI, Arial, sans-serif; max-width: 820px; margin: 40px auto; padding: 0 20px;
       line-height: 1.6; color: #222; }
h1 { font-size: 1.8em; border-bottom: 2px solid #ddd; padding-bottom: 8px; }
h2 { font-size: 1.3em; margin-top: 32px; color: #1a4d8f; }
a { color: #1a4d8f; }
li { margin-bottom: 6px; }
footer { margin-top: 40px; font-size: 0.85em; color: #777; }
@media print { body { margin: 0; } a { color: #222; } }
/* Our own page margins for the PDF: empty, except a page number at the bottom. Chrome/Edge (v131+) then
   leave out their default header and footer (file path, print date, page title). */
@page { margin: 18mm 15mm;
        @top-left { content: ""; } @top-center { content: ""; } @top-right { content: ""; }
        @bottom-left { content: ""; } @bottom-right { content: ""; }
        @bottom-center { content: counter(page) " / " counter(pages); font-size: 9pt; color: #777; } }
"""


def render(state: dict, draft: Draft | None) -> tuple[str, list[dict], list[str]]:
    """Return (markdown, kept sentences, dropped sentences)."""
    claims = {c["id"]: c for c in state["claims"]}
    sources = {s["id"]: s for s in state["sources"]}
    verified = {cid for cid, c in claims.items() if c["verdict"] == "supported"}
    kept: list[dict] = []
    dropped: list[str] = []

    def check(sentences: list[Sentence]) -> list[str]:
        """Keep sentences whose claims are all verified; return them as Markdown lines."""
        lines = []
        for s in sentences:
            if not s.claim_ids or not set(s.claim_ids) <= verified:
                dropped.append(s.text)
                continue
            source_ids = list(dict.fromkeys(claims[cid]["source_id"] for cid in s.claim_ids))
            kept.append({"text": s.text, "claim_ids": s.claim_ids, "source_ids": source_ids})
            lines.append(s.text + " " + "".join(f"[{sid}]" for sid in source_ids))
        return lines

    md = [f"# {draft.title if draft else state['question']}", "", f"**Question:** {state['question']}", ""]
    if draft:
        if summary := check(draft.summary):
            md += ["## Summary", "", " ".join(summary), ""]
        for section in draft.sections:
            if lines := check(section.sentences):
                md += [f"## {section.heading}", ""] + [f"- {line}" for line in lines] + [""]

    if state["conflicts"]:
        md += ["## Where sources disagree", ""] + [f"- {c}" for c in state["conflicts"]] + [""]

    thin = [sq for sq in state["sub_questions"] if sq["status"] == "thin"]
    if thin:
        md += ["## Not enough evidence", ""] + [f"- **{sq['text']}**: {sq['gap']}" for sq in thin] + [""]

    total = len(claims)
    md += ["## Verification", "", f"{len(verified)} of {total} claims passed verification; "
           f"{total - len(verified)} were rejected and left out of this report.", ""]

    cited = dict.fromkeys(sid for s in kept for sid in s["source_ids"])
    md += ["## Sources", ""] + [f"- [{sid}] [{sources[sid]['title']}]({sources[sid]['url']})" for sid in cited]
    return "\n".join(md) + "\n", kept, dropped


def to_html(report_md: str, title: str) -> str:
    """The Markdown report as one self-contained web page.

    It opens in any browser, so it can be shared by email or chat, and turned into a PDF with
    Print -> Save as PDF.
    """
    body = markdown.markdown(report_md)
    return f"""<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{html.escape(title)}</title>
<style>{PAGE_STYLE}</style>
</head>
<body>
{body}
<footer>Generated by DeepDive: every claim in this report was checked against the source it cites.</footer>
</body>
</html>
"""
